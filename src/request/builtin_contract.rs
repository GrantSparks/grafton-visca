// Internal contracts shared by the built-in request generator and its
// compile-fail fixtures. Keep this module independent of runtime machinery.

use crate::{Error, KnownState, ProfileSpec, StateKey, TargetRegistration};
use core::marker::PhantomData;

/// Value-dependent validation after the generated row gate.
pub(crate) trait BuiltinValidation {
    fn validate(&self, _profile: &ProfileSpec) -> Result<(), Error> {
        Ok(())
    }

    fn validate_target(&self, target: &TargetRegistration) -> Result<(), Error> {
        self.validate(target.profile())
    }

    fn pan_tilt_max_speed(&self) -> Option<u8> {
        None
    }
}

/// A state key and its exact value type, generated by `state_key_ledger!`.
pub(crate) trait StateValue {
    #[cfg(all(test, any(feature = "blocking", feature = "async")))]
    const KEY: StateKey;
    type Value;
    fn known(value: Self::Value) -> KnownState;
}

/// The only handwritten part of a known-state projection: its value.
///
/// `Set` and `Clear` require this method with the ledger key's exact value
/// type. There is deliberately no default and no overridable projection hook.
pub(crate) trait BuiltinStateValue<Value> {
    fn state_value(&self) -> Value;
}

pub(crate) struct NoState;
pub(crate) struct Set<K>(PhantomData<K>);
pub(crate) struct Clear<K>(PhantomData<K>);

/// The type-level key used by exhaustive ledger agreement tests.
#[cfg(all(test, any(feature = "blocking", feature = "async")))]
pub(crate) trait StateDescriptor {
    const KEY: Option<StateKey>;
    /// Exact state keys for an encoding-selected request whose rows differ.
    const BY_ROW: &'static [(crate::command::semantics::BuiltinCommand, Option<StateKey>)] = &[];
}

#[cfg(all(test, any(feature = "blocking", feature = "async")))]
impl StateDescriptor for NoState {
    const KEY: Option<StateKey> = None;
}
#[cfg(all(test, any(feature = "blocking", feature = "async")))]
impl<K: StateValue> StateDescriptor for Set<K> {
    const KEY: Option<StateKey> = Some(K::KEY);
}
#[cfg(all(test, any(feature = "blocking", feature = "async")))]
impl<K: StateValue> StateDescriptor for Clear<K> {
    const KEY: Option<StateKey> = Some(K::KEY);
}

/// Closed, inline effect on one write-only key.
///
/// Known values imply their key. A cleared limit is a typed known update,
/// whereas invalidation explicitly records that the key can no longer be trusted.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum AppliedStateProjection {
    Set(KnownState),
    Invalidate { key: StateKey },
}

impl AppliedStateProjection {
    pub(crate) const fn set(value: KnownState) -> Self {
        Self::Set(value)
    }
    pub(crate) const fn invalidate(key: StateKey) -> Self {
        Self::Invalidate { key }
    }
    pub(crate) const fn key(self) -> StateKey {
        match self {
            Self::Set(value) => value.key(),
            Self::Invalidate { key } => key,
        }
    }
    #[cfg(test)]
    pub(crate) const fn is_known(self) -> bool {
        matches!(self, Self::Set(_))
    }
}

/// The ledger-selected type generates the whole projection.
pub(crate) trait BuiltinStateProjection<R: ?Sized> {
    fn project(request: &R) -> Option<AppliedStateProjection>;
}

impl<R: ?Sized> BuiltinStateProjection<R> for NoState {
    fn project(_request: &R) -> Option<AppliedStateProjection> {
        None
    }
}

impl<K: StateValue, R: BuiltinStateValue<K::Value> + ?Sized> BuiltinStateProjection<R> for Set<K> {
    fn project(request: &R) -> Option<AppliedStateProjection> {
        Some(AppliedStateProjection::set(K::known(request.state_value())))
    }
}

impl<K: StateValue, R: BuiltinStateValue<K::Value> + ?Sized> BuiltinStateProjection<R>
    for Clear<K>
{
    fn project(request: &R) -> Option<AppliedStateProjection> {
        // Clear carries the typed known update chosen by the state key,
        // such as PanTiltLimitUpdate::clear, exactly as the cache expects.
        Some(AppliedStateProjection::set(K::known(request.state_value())))
    }
}
